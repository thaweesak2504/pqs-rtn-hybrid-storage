export type IntroductionContentAuthority = 'system' | 'document';

export interface IntroductionNestedItem {
  readonly id: string;
  readonly title: string;
  readonly content?: string;
}

export interface IntroductionSubItem {
  readonly id: string;
  readonly content: string;
  readonly nestedItems?: readonly IntroductionNestedItem[];
}

export interface IntroductionSectionContent {
  readonly id: string;
  readonly title: string;
  readonly content: string;
  readonly authority: IntroductionContentAuthority;
  readonly subItems?: readonly IntroductionSubItem[];
}

type GeneralIntroductionDefinition =
  | Omit<IntroductionSectionContent, 'subItems'>
  | {
    readonly id: string;
    readonly title: string;
    readonly authority: 'document';
    readonly contentPrefix: string;
  };

