export const createGeneralIntroductionSections = (
  appliedTo: string,
): readonly IntroductionSectionContent[] => GENERAL_INTRODUCTION_DEFINITIONS.map((section) => {
  if ('contentPrefix' in section) {
    return {
      id: section.id,
      title: section.title,
      authority: section.authority,
      content: `${section.contentPrefix} ${appliedTo}`,
    };
  }
  return section;
});

